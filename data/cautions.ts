/** 국가법령정보센터 주소를 만들어요. 예: law("농지법", "제8조") */
function law(name: string, article?: string): CautionSource {
  const path = name.replace(/\s/g, "");
  return {
    label: article ? `${name} ${article}` : name,
    url: article
      ? `https://www.law.go.kr/법령/${path}/${article}`
      : `https://www.law.go.kr/법령/${path}`,
  };
}

